const partialTranslations = Object.entries(exactTranslations)
  .filter(([ko]) => ko.length > 1)
  .sort(([a], [b]) => b.length - a.length);

const monthNames = ["", "Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];

export function translateText(input: string): string {
  if (!/[가-힣]/.test(input)) return input;
  const leading = input.match(/^\s*/)?.[0] ?? "";
  const trailing = input.match(/\s*$/)?.[0] ?? "";
  const core = input.trim();
  const exact = exactTranslations[core];
  if (exact) return `${leading}${exact}${trailing}`;
  let translated = core;
  for (const [ko, en] of partialTranslations) translated = translated.replaceAll(ko, en);
  translated = translated
    .replace(/^연\s+/, "Annual ")
    .replace(/(\d+)개월\s*전/g, "$1-month lag")
    .replace(/(\d+)개월/g, "$1 months")
    .replace(/(20\d{2})년\s*(1[0-2]|0?[1-9])월/g, (_, year: string, month: string) => `${monthNames[Number(month)]} ${year}`)
    .replace(/(1[0-2]|0?[1-9])월/g, (_, month: string) => monthNames[Number(month)])
    .replace(/([1-4])분기/g, (_, quarter: string) => `Q${quarter}`)
    .replace(/(\d+)개/g, "$1")
    .replace(/(\d+)년/g, "$1 years")
    .replace(/님(?=\s|$)/g, "");
  for (const [ko, en] of replacements) translated = translated.replaceAll(ko, en);
  translated = translated.replace(/\b(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)(?:은|는|이|가|에|을|를|부터|까지)/g, "$1");
  return `${leading}${translated}${trailing}`;
}

type I18nValue = { language: Language; setLanguage: (language: Language) => void; t: (text: string) => string };
const I18nContext = createContext<I18nValue | null>(null);
const originalText = new WeakMap<Text, string>();
const originalAttributes = new WeakMap<Element, Map<string, string>>();
const translatedAttributes = ["aria-label", "title", "placeholder"];

function translateNode(node: Node, language: Language) {
  if (node.nodeType === Node.TEXT_NODE) {
    const text = node as Text;
    if (text.parentElement?.closest("[data-no-translate], script, style")) return;
    const stored = originalText.get(text);
    if (language === "ko") {
      if (stored !== undefined && text.data !== stored) text.data = stored;
      return;
    }
    if (stored !== undefined && text.data === translateText(stored)) return;
    const source = stored !== undefined && text.data === stored ? stored : text.data;
    originalText.set(text, source);
    const translated = translateText(source);
    if (translated !== text.data) text.data = translated;
    return;
  }
  if (!(node instanceof Element) || node.closest("[data-no-translate]")) return;
  let originals = originalAttributes.get(node);
  if (!originals) {
    originals = new Map();
    originalAttributes.set(node, originals);
  }
  for (const attribute of translatedAttributes) {
    const current = node.getAttribute(attribute);
    if (current === null) continue;
    const stored = originals.get(attribute);
    if (language === "ko") {
      if (stored !== undefined && current !== stored) node.setAttribute(attribute, stored);
    } else {
      if (stored !== undefined && current === translateText(stored)) continue;
      const source = stored !== undefined && current === stored ? stored : current;
      originals.set(attribute, source);
      node.setAttribute(attribute, translateText(source));
    }
  }
}

function translateTree(root: Node, language: Language) {
  translateNode(root, language);
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) translateNode(walker.currentNode, language);
}

function PageTranslator({ language }: { language: Language }) {
  useEffect(() => {
    document.documentElement.lang = language;
    const root = document.getElementById("root");
    if (!root) return;
    translateTree(root, language);
    const observer = new MutationObserver((mutations) => {
      for (const mutation of mutations) {
        if (mutation.type === "characterData") translateNode(mutation.target, language);
        mutation.addedNodes.forEach((node) => translateTree(node, language));
        if (mutation.type === "attributes") translateNode(mutation.target, language);
      }
    });
    observer.observe(root, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: translatedAttributes });
    return () => observer.disconnect();
  }, [language]);
  return null;
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => localStorage.getItem("ship-signal-language") === "en" ? "en" : "ko");
  const setLanguage = (next: Language) => {
    localStorage.setItem("ship-signal-language", next);
    setLanguageState(next);
  };
  const value = useMemo(() => ({ language, setLanguage, t: (text: string) => language === "en" ? translateText(text) : text }), [language]);
  return <I18nContext.Provider value={value}><PageTranslator language={language} />{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used within I18nProvider");
  return context;
}

export function LanguageSwitcher({ compact = false }: { compact?: boolean }) {
  const { language, setLanguage } = useI18n();
  return <div className={`inline-flex items-center rounded-lg border border-slate-200 bg-white p-1 shadow-sm ${compact ? "text-[11px]" : "text-xs"}`} aria-label="언어 설정" data-no-translate>
    <button type="button" lang="ko" aria-pressed={language === "ko"} onClick={() => setLanguage("ko")} className={`rounded-md px-2.5 py-1.5 font-semibold transition-colors ${language === "ko" ? "bg-slate-900 text-white" : "text-slate-500 hover:bg-slate-100"}`}>한국어</button>
    <button type="button" lang="en" aria-pressed={language === "en"} onClick={() => setLanguage("en")} className={`rounded-md px-2.5 py-1.5 font-semibold transition-colors ${language === "en" ? "bg-slate-900 text-white" : "text-slate-500 hover:bg-slate-100"}`}>English</button>
  </div>;
}
